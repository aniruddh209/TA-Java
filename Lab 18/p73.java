public class p73 {
    public static void main(String[] args) {

        System.out.println("Min = " + Math.min(10, 20));

        System.out.println("Max = " + Math.max(10, 20));

        System.out.println("Random = " + Math.random());

        System.out.println("Power = " + Math.pow(2, 3));

        System.out.println("Square Root = " + Math.sqrt(25));

        System.out.println("Round = " + Math.round(12.56));

        System.out.println("Ceil = " + Math.ceil(12.12));

        System.out.println("Floor = " + Math.floor(12.99));

        System.out.println("Absolute = " + Math.abs(-25));
    }
}